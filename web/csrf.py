"""CSRF synchronizer-token protection for state-mutating HTML forms.

Tokens are stateless: an `itsdangerous` signature over the user's session
cookie value with a 1-hour expiry. Because the token is bound to the session
cookie, it invalidates automatically when the session changes (logout, login,
expiry).

API routes under `/api/*` use Bearer/X-API-Key auth and are intentionally
exempt — browsers don't send `Authorization` headers cross-origin without an
explicit `fetch`, so CSRF doesn't apply.

Usage in a route:

    from web.csrf import verify_csrf
    @router.post("/secrets")
    async def secrets_create(... , _csrf=Depends(verify_csrf)):
        ...

Usage in a template:

    <form method="post" action="/secrets">
      <input type="hidden" name="csrf_token" value="{{ csrf_token }}">
      ...
    </form>

In tests, bypass with:

    from web.csrf import verify_csrf
    app.dependency_overrides[verify_csrf] = lambda: None
"""
from itsdangerous import URLSafeTimedSerializer
from fastapi import HTTPException, Request

_MAX_AGE_SECONDS = 3600  # tokens valid for one hour
_SALT = "csrf-v1"


def generate_csrf_token(session_cookie: str, signing_key: bytes) -> str:
    """Return a signed token bound to `session_cookie`. Safe for empty sessions
    (first-run /setup needs a token before any session exists)."""
    return URLSafeTimedSerializer(signing_key).dumps(session_cookie, salt=_SALT)


def validate_csrf_token(token: str, session_cookie: str, signing_key: bytes) -> bool:
    """Return True iff `token` was generated by `generate_csrf_token` for the
    given `session_cookie` and is within the max-age window."""
    if not token:
        return False
    try:
        value = URLSafeTimedSerializer(signing_key).loads(
            token, salt=_SALT, max_age=_MAX_AGE_SECONDS
        )
        return value == session_cookie
    except Exception:
        return False


def csrf_token_for(request: Request) -> str:
    """Generate a CSRF token for the given request's session. Use in _ctx()
    helpers when rendering templates that contain mutating forms."""
    from web.auth import get_auth_config
    session = request.cookies.get("session", "")
    cfg = get_auth_config()
    return generate_csrf_token(session, cfg["signing_key"])


async def verify_csrf(request: Request) -> None:
    """FastAPI dependency. Raises 403 if the request lacks a valid csrf_token.

    Reads the form body, so this must only be used on POST/PUT/DELETE routes
    that accept form-encoded bodies (the default for HTML <form> submission).
    """
    from web.auth import get_auth_config
    session = request.cookies.get("session", "")
    form = await request.form()
    token = form.get("csrf_token", "")
    cfg = get_auth_config()
    if not validate_csrf_token(token, session, cfg["signing_key"]):
        raise HTTPException(status_code=403, detail="Invalid CSRF token")
